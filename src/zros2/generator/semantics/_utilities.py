"""Shared utilities for code generation — header comment, naming, defaults.

Type-pattern detection is delegated to the Lark-based
:mod:`zros2.generator.parsing._types` parser."""

import datetime
import hashlib
import re
from importlib.metadata import PackageNotFoundError
from importlib.metadata import version as _pkg_version

from lark import LarkError

from zros2.generator.parsing._types import parse_type

try:
    _PKG_VERSION: str = _pkg_version("zros2")
except PackageNotFoundError:  # source tree without installed metadata
    _PKG_VERSION = "0.0.0"


# ═══════════════════════════════════════════════════════════════════════════
# Header comment
# ═══════════════════════════════════════════════════════════════════════════


def header_comment(content: str = "", distro: str = "") -> str:
    """Return a "do not modify" header with timestamp and content SHA1.

    The hash is computed from *content* (everything after the header block).
    If *content* is empty the hash line is omitted (e.g. for the registry
    module which is built once at module load time).
    """
    ts = datetime.datetime.now(datetime.UTC).isoformat(timespec="seconds")
    lines = [
        f"# This file is auto-generated by zros2-gen v{_PKG_VERSION}. DO NOT MODIFY.",
    ]
    if content:
        sha = hashlib.sha1(content.encode("utf-8")).hexdigest()
        lines.append(f"# SHA1: {sha}")
    if distro:
        lines.append(f"# ROS 2 distro: {distro}")
    lines.append(f"# Generated at: {ts}")
    lines.append("")
    return "\n".join(lines) + "\n"


# ═══════════════════════════════════════════════════════════════════════════
# Naming
# ═══════════════════════════════════════════════════════════════════════════


def to_snake_case(name: str) -> str:
    """Convert PascalCase to snake\\_case, preserving existing underscores."""
    parts = name.split("_")
    converted: list[str] = []
    for part in parts:
        s = re.sub(r"(.)([A-Z][a-z]+)", r"\1_\2", part)
        s = re.sub(r"([a-z0-9])([A-Z])", r"\1_\2", s)
        converted.append(s.lower())
    return "_".join(converted)


# ═══════════════════════════════════════════════════════════════════════════
# Default value expressions
# ═══════════════════════════════════════════════════════════════════════════


def default_expr(type_str: str) -> str:
    """Return a Python default-value expression for a ROS 2 type.

    **Deprecated compatibility API:** callers should use
    :func:`._literal_values.default_scalar` plus
    :func:`zros2.generator.codegen._literal_ast.literal_ast`. The stub renderer
    no longer uses this helper; it remains only for older callers.
    """
    try:
        info = parse_type(type_str)
    except LarkError:
        return "None"

    base = info.base_name

    # Arrays / sequences keep their text representation for compatibility.
    if info.kind in ("unbounded", "unbounded_sequence"):
        return "()"
    if info.kind == "fixed" and base == "uint8" and info.array_size:
        return f"(0,) * {info.array_size}"
    if info.kind in ("fixed", "bounded", "bounded_sequence"):
        return "()"
    if base in ("time", "duration"):
        return "None"

    from zros2.generator.semantics._literal_values import default_scalar

    try:
        value = default_scalar(info)
    except ValueError:
        return "None"
    if isinstance(value, str):
        return f'"{value}"'
    return repr(value)
